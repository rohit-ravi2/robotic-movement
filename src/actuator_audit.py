"""Menagerie-wide actuator semantics audit. Direct model inspection."""
import os, json, glob, mujoco, numpy as np
MEN = os.environ.get("MENAGERIE_DIR", os.path.join(os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")), "models", "mujoco_menagerie"))
HUM = ["unitree_g1", "unitree_h1", "unitree_h1_2", "booster_t1", "apptronik_apollo", "berkeley_humanoid",
       "fourier_n1", "pal_talos", "robotis_op3", "toddlerbot_2xc", "kuavo_s45", "agility_cassie", "boston_dynamics_spot"]
BT = {0: "none", 1: "affine", 2: "muscle", 3: "user"}; GT = {0: "fixed", 1: "affine", 2: "muscle", 3: "user"}
reg = {}
for name in sorted(os.listdir(MEN)):
    dpath = f"{MEN}/{name}"
    if not os.path.isdir(dpath): continue
    xmls = [f for f in ("scene.xml", "scene_mjx.xml") if os.path.exists(f"{dpath}/{f}")]
    for x in xmls:
        try: m = mujoco.MjModel.from_xml_path(f"{dpath}/{x}")
        except Exception as e: continue
        free = any(m.jnt_type[j] == 0 for j in range(m.njnt))
        if m.nu < 10 or not free: continue          # legged/humanoid-scale floating-base robots only
        kinds = []
        for a in range(m.nu):
            bt, gt = int(m.actuator_biastype[a]), int(m.actuator_gaintype[a])
            kp = float(m.actuator_gainprm[a][0]); b1, b2 = float(m.actuator_biasprm[a][1]), float(m.actuator_biasprm[a][2])
            if bt == 0 and gt == 0: k = "torque_motor"
            elif bt == 1 and abs(b1 + kp) < 1e-9 and b1 != 0: k = "position_servo"
            elif bt == 1 and b1 == 0 and b2 != 0: k = "velocity_servo"
            else: k = f"other(gain {GT[gt]}, bias {BT[bt]})"
            kinds.append(dict(kind=k, kp=kp, kv=-b2, ctrlrange=m.actuator_ctrlrange[a].tolist() if m.actuator_ctrllimited[a] else None,
                              forcerange=m.actuator_forcerange[a].tolist() if m.actuator_forcelimited[a] else None,
                              gear=float(m.actuator_gear[a][0])))
        jfr = int(sum(m.jnt_actfrclimited))
        summ = {}
        for k in kinds: summ[k["kind"]] = summ.get(k["kind"], 0) + 1
        kps = sorted({round(k["kp"], 3) for k in kinds if k["kind"] == "position_servo"})
        reg[f"{name}/{x}"] = dict(nu=int(m.nu), njnt=int(m.njnt), floating_base=free, kinds=summ,
                                  position_kp_values=kps[:8], joints_with_actuatorfrcrange=jfr,
                                  any_forcelimited=int(sum(m.actuator_forcelimited)),
                                  hidden_default_note=("joint-level actuatorfrcrange clamps total joint torque (second clamp layer)" if jfr else ""),
                                  actuators=kinds)
json.dump(reg, open(os.path.join(os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")), "results/robot_actuator_registry.json"), "w"), indent=1)
lines = ["# ROBOT_ACTUATOR_SEMANTICS", "", "Generated by `src/actuator_audit.py` from direct inspection of every MuJoCo Menagerie model with a floating base and >= 10 actuators. Machine-readable registry: `results/robot_actuator_registry.json`.", "",
         "| model | nu | actuator kinds | position kp values | joints with actuatorfrcrange | actuators force-limited |", "|---|---|---|---|---|---|"]
for k, v in reg.items():
    lines.append(f"| {k} | {v['nu']} | {', '.join(f'{a}: {b}' for a, b in v['kinds'].items())} | {v['position_kp_values']} | {v['joints_with_actuatorfrcrange']} | {v['any_forcelimited']} |")
lines += ["", "Rules this project applies (enforced by PCTV-1/6/9):",
          "- A position servo's ctrl is a TARGET ANGLE; its ctrlrange is in radians. Never read it as torque (defects P1, P9).",
          "- Joint-level `actuatorfrcrange` is a second clamp on total joint torque; any capacity change must set it too (defect P6, second layer).",
          "- The G1 torque conversion is NOT assumed to transfer: each robot needs its own adapter verified by PCTV-1..9."]
open(os.path.join(os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")), "ROBOT_ACTUATOR_SEMANTICS.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines[4:]))
